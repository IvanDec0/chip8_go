// FontRenderer handles bitmap font rendering
type FontRenderer struct {
	charWidth  int
	charHeight int
}

// NewFontRenderer creates a new font renderer with 8x8 character dimensions
func NewFontRenderer() *FontRenderer {
	return &FontRenderer{
		charWidth:  8,
		charHeight: 8,
	}
}

// RenderChar renders a single character at the specified position
func (fr *FontRenderer) RenderChar(renderer *sdl.Renderer, char rune, x, y int, color menu.Color) error {
	bitmap, exists := fontBitmaps[char]
	if !exists {
		// If character not found, use space
		bitmap = fontBitmaps[' ']
	}

	// Set the drawing color
	renderer.SetDrawColor(color.R, color.G, color.B, color.A)

	// Render each row of the character
	for row := 0; row < fr.charHeight; row++ {
		rowData := bitmap[row]
		for col := 0; col < fr.charWidth; col++ {
			// Check if bit is set (pixel should be drawn)
			if (rowData & (0x80 >> col)) != 0 {
				// Draw pixel as a 1x1 rectangle
				rect := sdl.Rect{
					X: int32(x + col),
					Y: int32(y + row),
					W: 1,
					H: 1,
				}
				err := renderer.FillRect(&rect)
				if err != nil {
					return err
				}
			}
		}
	}

	return nil
}

// RenderString renders a string of characters at the specified position
func (fr *FontRenderer) RenderString(renderer *sdl.Renderer, text string, x, y int, color menu.Color) error {
	currentX := x

	for _, char := range text {
		err := fr.RenderChar(renderer, char, currentX, y, color)
		if err != nil {
			return err
		}
		currentX += fr.charWidth
	}

	return nil
}

// GetTextDimensions calculates the width and height of a text string
func (fr *FontRenderer) GetTextDimensions(text string) (width, height int) {
	// Count the actual characters (runes) in the string
	runeCount := 0
	for range text {
		runeCount++
	}

	width = runeCount * fr.charWidth
	height = fr.charHeight
	return
}

// GetCharWidth returns the width of a single character
func (fr *FontRenderer) GetCharWidth() int {
	return fr.charWidth
}

// GetCharHeight returns the height of a single character
func (fr *FontRenderer) GetCharHeight() int {
	return fr.charHeight
}
